// ---------------- AUDIO (WAV files are generated automatically) ----------------
// Only WinMM is required. In CodeBlocks/MinGW add: -lwinmm
void writeWavHeader(FILE* f, int sampleRate, int samples) {
    int dataBytes = samples * 2;
    int riffSize = 36 + dataBytes;
    short audioFormat = 1, channels = 1, bitsPerSample = 16, blockAlign = 2;
    int byteRate = sampleRate * blockAlign, subChunk1 = 16;
    fwrite("RIFF", 1, 4, f); fwrite(&riffSize, 4, 1, f);
    fwrite("WAVEfmt ", 1, 8, f); fwrite(&subChunk1, 4, 1, f);
    fwrite(&audioFormat, 2, 1, f); fwrite(&channels, 2, 1, f);
    fwrite(&sampleRate, 4, 1, f); fwrite(&byteRate, 4, 1, f);
    fwrite(&blockAlign, 2, 1, f); fwrite(&bitsPerSample, 2, 1, f);
    fwrite("data", 1, 4, f); fwrite(&dataBytes, 4, 1, f);
}

void createAudioFiles() {
    const int rate = 22050;

    // The person's spoken "Help! Help!" is generated by Windows Speech
    // at runtime, so no recorded scream WAV is required.

    // Alternating high/low emergency siren, suitable for the ambulance.
    {
        FILE* f = fopen("ambulance_siren.wav", "wb");
        if (f) {
            const float duration = 2.0f;
            int count = (int)(rate * duration);
            writeWavHeader(f, rate, count);
            for (int i = 0; i < count; ++i) {
                float t = (float)i / rate;
                // Traditional ambulance "nee-naw" two-tone siren:
                // alternate steadily between two clear pitches.
                int tone = ((int)(t * 2.4f)) % 2;
                float freq = tone ? 960.0f : 680.0f;
                float sampleValue = sinf(2.0f * PI * freq * t);
                short sample = (short)(sampleValue * 10000.0f);
                fwrite(&sample, sizeof(short), 1, f);
            }
            fclose(f);
        }
    }
}

// Users can choose their own WAV files with Windows file-picker dialogs.
PROCESS_INFORMATION helpVoiceProcess = {};

void playPersonScream() {
    // Use Windows' built-in speech voice to repeatedly say "Help! Help!"
    // The voice runs in a separate hidden PowerShell process.
    FILE* f = fopen("person_help_voice.ps1", "w");
    if (!f) return;
    const char* script =
        "Add-Type -AssemblyName System.Speech\r\n"
        "$v = New-Object System.Speech.Synthesis.SpeechSynthesizer\r\n"
        "$v.Rate = 0\r\n"
        "$v.Volume = 100\r\n"
        "while ($true) { $v.Speak('Help! Help! Please help me!') }\r\n";
    fputs(script, f);
    fclose(f);

    STARTUPINFOA si = {};
    si.cb = sizeof(si);
    si.dwFlags = STARTF_USESHOWWINDOW;
    si.wShowWindow = SW_HIDE;
    char command[] = "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File person_help_voice.ps1";
    CreateProcessA(NULL, command, NULL, NULL, FALSE, CREATE_NO_WINDOW,
                   NULL, NULL, &si, &helpVoiceProcess);
}
void playAmbulanceSiren() {
    // Repeated traditional two-tone ambulance siren ("nee-naw").
    PlaySoundA("ambulance_siren.wav", NULL, SND_FILENAME | SND_ASYNC | SND_LOOP);
}
void stopAudio() {
    PlaySoundA(NULL, NULL, 0);
    if (helpVoiceProcess.hProcess) {
        TerminateProcess(helpVoiceProcess.hProcess, 0);
        CloseHandle(helpVoiceProcess.hProcess);
        CloseHandle(helpVoiceProcess.hThread);
        helpVoiceProcess = {};
    }
}

float rnd(float a, float b) { return a + (b - a) * (rand() % 1000) / 1000.0f; }

void emit(int type, float x, float y, float z, float vx, float vy, float vz, float life, float size) {
    for (int i = 0; i < MAXP; i++) {
        if (!ps[i].alive) {
            P p = {x, y, z, vx, vy, vz, life, life, size, type, true};
            ps[i] = p;
            return;
        }
    }
}

bool sirenOn() { return stage >= S_DISPATCH && stage < S_DONE; }

float fireIntensity() {
    if (!fireOn) return 0;
    return burn * (0.8f + 0.2f * sinf(tick * 0.15f));
}

void emitEffects() {
    float I = fireIntensity();
    if (I > 0.01f) {
        int n = (int)(I * 7) + 1;
        for (int i = 0; i < n; i++)
            emit(0, FIREX + rnd(-0.5f, 0.5f), FIREY - 0.4f + rnd(0, 0.5f), FIREZ + rnd(0, 0.4f),
                 rnd(-0.2f, 0.2f), rnd(1, 2.5f) * (0.5f + I), rnd(0, 0.3f), rnd(0.5f, 1.0f), 8 + 8 * I);
        if (rand() % 100 < 70 * I)
            emit(1, FIREX + rnd(-0.4f, 0.4f), FIREY + 0.8f, FIREZ + 0.2f,
                 rnd(0, 0.5f), rnd(1.5f, 3), rnd(0, 0.3f), rnd(2.5f, 4), 14);
        if (rand() % 100 < 12 * I)
            emit(2, FIREX + rnd(-0.4f, 0.4f), FIREY, FIREZ + 0.2f,
                 rnd(-2, 2), rnd(3, 6), rnd(0, 2), rnd(0.5f, 1.0f), 3);
    }
    if (stage == S_SPRAY) {
        float a = ladderAng * PI / 180, L = 4.2f + ext;
        float tx = truckX - 1.0f, ty = 2.4f + sinf(a) * L, tz = truckZ - cosf(a) * L;
        float dx = FIREX - tx, dy = FIREY - ty, dz = FIREZ - tz;
        float d = sqrtf(dx * dx + dy * dy + dz * dz);
        for (int i = 0; i < 6; i++)
            emit(3, tx, ty, tz, dx / d * 7 + rnd(-0.4f, 0.4f), dy / d * 7 + rnd(-0.2f, 0.6f) + 1,
                 dz / d * 7 + rnd(-0.4f, 0.4f), 1.5f, 5);
    }
}

void updateParticles() {
    float dt = 0.016f;
    for (int i = 0; i < MAXP; i++) {
        P &p = ps[i];
        if (!p.alive) continue;
        p.life -= dt;
        if (p.life <= 0) { p.alive = false; continue; }
        p.x += p.vx * dt; p.y += p.vy * dt; p.z += p.vz * dt;
        if (p.type == 0) { p.vx += rnd(-0.5f, 0.5f) * dt * 4; p.vy += dt; }
        else if (p.type == 1) { if (p.size < 40) p.size += dt * 10; p.vx += 0.3f * dt; }
        else if (p.type == 2) { p.vy -= 9 * dt; if (p.y < 0) p.alive = false; }
        else {
            p.vy -= 3 * dt;
            if (p.y < 0.05f) p.alive = false;
            if (p.z < -5.5f && fabsf(p.x - FIREX) < 1.3f && p.y > 6.6f && p.y < 9.2f) {
                p.alive = false;
                if (burn > 0) burn -= 0.0006f;
            }
        }
    }
}

void drawParticles() {
    glDisable(GL_LIGHTING);
    glDepthMask(GL_FALSE);
    glEnable(GL_BLEND);
    glEnable(GL_POINT_SMOOTH);
    for (int pass = 0; pass < 2; pass++) {
        if (pass == 0) glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
        else glBlendFunc(GL_SRC_ALPHA, GL_ONE);
        for (int i = 0; i < MAXP; i++) {
            P &p = ps[i];
            if (!p.alive) continue;
            bool normalPass = (p.type == 1 || p.type == 3);
            if (normalPass != (pass == 0)) continue;
            float t = p.life / p.maxl;
            if (p.type == 0) glColor4f(1, 0.25f + 0.6f * t, 0.05f, t);
            else if (p.type == 1) glColor4f(0.25f, 0.25f, 0.25f, 0.5f * t);
            else if (p.type == 2) glColor4f(1, 0.9f, 0.4f, t);
            else glColor4f(0.4f, 0.7f, 1, 0.8f);
            glPointSize(p.size);
            glBegin(GL_POINTS);
            glVertex3f(p.x, p.y, p.z);
            glEnd();
        }
    }
    glDepthMask(GL_TRUE);
    glDisable(GL_BLEND);
    glEnable(GL_LIGHTING);
}

GLuint makeTex(int type) {
    const int N = 64;
    static unsigned char img[N][N][3];
    for (int y = 0; y < N; y++)
        for (int x = 0; x < N; x++) {
            int n = rand() % 20;
            int r, g, b;
            if (type == 0) {
                bool mortar = (y % 16 < 2) || (((x + ((y / 16) % 2) * 16) % 32) < 2);
                if (mortar) { r = 190; g = 190; b = 180; }
                else { r = 150 + n; g = 70 + n / 2; b = 50 + n / 2; }
            } else {
                r = g = b = 55 + n;
                if (y >= 30 && y < 34 && (x % 32) < 18) { r = 230; g = 200; b = 40; }
            }
            img[y][x][0] = (unsigned char)r;
            img[y][x][1] = (unsigned char)g;
            img[y][x][2] = (unsigned char)b;
        }
    GLuint t;
    glGenTextures(1, &t);
    glBindTexture(GL_TEXTURE_2D, t);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_REPEAT);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_REPEAT);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGB, N, N, 0, GL_RGB, GL_UNSIGNED_BYTE, img);
    return t;
}

void box(float sx, float sy, float sz, GLuint tex, float rep) {
    if (!tex) {
        glDisable(GL_TEXTURE_2D);
        glPushMatrix(); glScalef(sx, sy, sz); glutSolidCube(1); glPopMatrix();
        return;
    }
    glEnable(GL_TEXTURE_2D);
    glBindTexture(GL_TEXTURE_2D, tex);
    float x = sx / 2, y = sy / 2, z = sz / 2;
    float v[8][3] = {{-x,-y,-z},{x,-y,-z},{x,y,-z},{-x,y,-z},{-x,-y,z},{x,-y,z},{x,y,z},{-x,y,z}};
    int f[6][4] = {{4,5,6,7},{1,0,3,2},{0,4,7,3},{5,1,2,6},{3,7,6,2},{0,1,5,4}};
    float n[6][3] = {{0,0,1},{0,0,-1},{-1,0,0},{1,0,0},{0,1,0},{0,-1,0}};
    float tc[4][2] = {{0,0},{1,0},{1,1},{0,1}};
    glBegin(GL_QUADS);
    for (int i = 0; i < 6; i++) {
        glNormal3fv(n[i]);
        for (int j = 0; j < 4; j++) {
            glTexCoord2f(tc[j][0] * rep, tc[j][1] * rep);
            glVertex3fv(v[f[i][j]]);
        }
    }
    glEnd();
    glDisable(GL_TEXTURE_2D);
}

void cube(float x, float y, float z, float sx, float sy, float sz) {
    glPushMatrix();
    glTranslatef(x, y, z);
    box(sx, sy, sz, 0, 1);
    glPopMatrix();
}

