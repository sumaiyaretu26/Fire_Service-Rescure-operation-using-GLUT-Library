void setCamera() {
    float ex, ey, ez, cx, cy, cz;
    if (camMode == 1) {
        cx = 4; cy = 3; cz = -3;
        ex = cx + camDist * cosf(camPitch) * sinf(camYaw);
        ey = cy + camDist * sinf(camPitch);
        ez = cz + camDist * cosf(camPitch) * cosf(camYaw);
    } else if (camMode == 2) {
        ex = truckX - 6; ey = 4; ez = truckZ + 7;
        cx = truckX + 3; cy = 1.8f; cz = truckZ;
    } else if (camMode == 3) {
        ex = 17.5f; ey = 3.2f; ez = 5;
        cx = 16; cy = 1.5f; cz = -3;
    } else {
        ex = flyX; ey = flyY; ez = flyZ;
        cx = ex + sinf(flyYaw) * cosf(flyPitch);
        cy = ey + sinf(flyPitch);
        cz = ez - cosf(flyYaw) * cosf(flyPitch);
    }
    gluLookAt(ex, ey, ez, cx, cy, cz, 0, 1, 0);
}

