void building(float x, float z, float w, float h, float d, int s, bool burning) {
    glPushMatrix();
    glTranslatef(x, h / 2, z);
    glColor3f(1, 1, 1);
    box(w, h, d, texWall, 3);
    glPopMatrix();

    float zf = z + s * (d / 2 + 0.02f);
    for (int wy = 4; wy < h - 1; wy += 2) {
        for (int c = 0; c < (int)(w / 2); c++) {
            float wx = x - w / 2 + 1 + 2 * c;
            if (nightMode) glDisable(GL_LIGHTING);
            if (burning && c == 0 && wy == 8 && fireOn) glColor3f(0.1f, 0.05f, 0.05f);
            else if (nightMode) glColor3f(1, 0.9f, 0.5f);
            else glColor3f(0.55f, 0.75f, 0.9f);
            cube(wx, (float)wy, zf, 1.0f, 1.2f, 0.1f);
            if (nightMode) glEnable(GL_LIGHTING);

            balcony(wx, (float)wy - 0.55f, zf, s);
        }
    }
}

