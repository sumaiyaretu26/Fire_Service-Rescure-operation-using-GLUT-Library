bool follow(float &x, float &z, float p[][2], int n, int &i, float sp, float &h) {
    if (i >= n) return true;
    float dx = p[i][0] - x, dz = p[i][1] - z;
    float d = sqrtf(dx * dx + dz * dz);
    if (d > 0.01f) {
        float target = atan2f(-dz, dx) * 57.2958f;
        float diff = target - h;
        while (diff > 180) diff -= 360;
        while (diff < -180) diff += 360;
        h += diff * 0.12f;
    }
    if (d <= sp) { x = p[i][0]; z = p[i][1]; i++; return i >= n; }
    x += dx / d * sp;
    z += dz / d * sp;
    return false;
}

void resetAll() {
    stopAudio();
    stage = S_IDLE; fireOn = false; burn = 0; paused = false;
    truckX = -18; truckZ = -3.8f; truckH = -90; truckWp = 0;
    turntable = ladderAng = ext = 0;
    rphase = 0; fwp = 0; waitT = 0;
    f2x = 9; f2z = -0.5f; f2h = 0; f2wp = 0; f2Moving = false;
    ambOn = false; ambX = -26; ambZ = 1.8f; ambH = 0; ambWp = 0;
    car1X = -45.0f; car2X = 35.0f;
    for (int i = 0; i < MAXP; i++) ps[i].alive = false;
    message = "Press F to start the fire";
}

void update(int v) {
    if (!paused) {
        tick++;

        car1X += 0.22f; if (car1X > 60.0f) car1X = -60.0f;
        car2X -= 0.28f; if (car2X < -60.0f) car2X = 60.0f;

        if (fireOn && stage < S_SPRAY && burn < 1) burn += 0.0006f;

        switch (stage) {
        case S_DISPATCH:
            message = "Fire truck & Ambulance are on the way!";
            if (follow(truckX, truckZ, truckPath, 2, truckWp, 0.12f, truckH)) { truckH = 0; stage = S_SETUP; }
            break;
        case S_SETUP:
            message = "Truck arrived - extending telescopic ladder";
            if (turntable < 90) turntable += 1.5f;
            else if (ladderAng < 55) ladderAng += 0.8f;
            else if (ext < 1.2f) ext += 0.03f;
            else stage = S_SPRAY;
            break;
        case S_SPRAY:
            message = "Firefighters are spraying water on the fire";
            if (burn <= 0.02f) {
                burn = 0; fireOn = false;
                stage = S_RESCUE; rphase = 0;
                fx = 10; fz = -0.5f; fh = 0; fwp = 0;
                f2x = 9; f2z = -0.5f; f2h = 0; f2wp = 0; f2Moving = true;
            }
            break;
        case S_RESCUE:
            if (rphase == 0) {
                message = "Firefighters are entering the building";
                f2Moving = !follow(f2x, f2z, pathIn2, 2, f2wp, 0.06f, f2h);
                if (follow(fx, fz, pathIn, 2, fwp, 0.06f, fh)) { rphase = 1; waitT = 100; }
            } else if (rphase == 1) {
                message = "Reaching the trapped person at the balcony...";
                f2Moving = false;
                if (--waitT <= 0) {
                    rphase = 2; fwp = 0; fx = 13; fz = -5.4f; fh = -90;
                    f2wp = 0;
                }
            } else if (rphase == 2) {
                message = "Carrying the person to the Ambulance!";
                f2Moving = !follow(f2x, f2z, pathOut2, 2, f2wp, 0.05f, f2h);
                if (follow(fx, fz, pathOut, 2, fwp, 0.05f, fh)) { rphase = 3; stage = S_DONE; }
            }
            break;
        case S_DONE:
            message = "Rescue complete! Person is safe with Ambulance. Press R to restart";
            stopAudio();
            f2Moving = !follow(f2x, f2z, pathOut2, 2, f2wp, 0.05f, f2h);
            break;
        default: break;
        }

        if (ambOn) follow(ambX, ambZ, ambPath, 2, ambWp, 0.11f, ambH);

        emitEffects();
        updateParticles();
        if (burn < 0) burn = 0;
        if (burn > 1) burn = 1;
    }
    glutPostRedisplay();
    glutTimerFunc(16, update, 0);
}

